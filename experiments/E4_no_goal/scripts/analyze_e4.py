"""E4 analysis: tables with n and bootstrap CI95, survival curves, verdicts.

Reads experiments/E4_no_goal/results/*.json, writes results/summary.json and
results/tables.md. Every mean carries a percentile bootstrap CI95 (10k resamples)
and every arm states its n.
"""

from __future__ import annotations

import glob
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import boot_ci, boot_diff_ci, dump_json, fmt_ci  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.abspath(os.path.join(HERE, "..", "results"))

ARM_ORDER = ["random", "safe_random", "a0g0", "a0g0_eq", "a1g0", "a1g0_eq", "a1g0_eqN",
             "killdead_only", "a0g1", "a0g1_noslack", "a1g1"]
ARM_LABEL = {
    "random": "uniform random",
    "safe_random": "safe random (1-step viability filter)",
    "a0g0": "a=0 g=0 (Common Sense, diversity only)",
    "a0g0_eq": "a=0 g=0 @ equal budget (M x13)",
    "a1g0": "a=1 g=0 (canonical FMC)",
    "a1g0_eq": "a=1 g=0 @ equal budget, deeper (M x13)",
    "a1g0_eqN": "a=1 g=0 @ equal budget, wider (N x13)",
    "killdead_only": "a=0, kill_dead only (Phi exponent inert, 1e-12)",
    "a0g1": "a=0 g=1 (the E4 agent: no goal, Phi only)",
    "a0g1_noslack": "a=0 g=1, Phi without fuel slack",
    "a1g1": "a=1 g=1 (SPEC section 6 pilot)",
}
HAZARD = {"trap", "pit", "dead"}
CURVE_T = [5, 10, 15, 20, 25, 30, 35, 40]


def load():
    data = {}
    for p in sorted(glob.glob(os.path.join(RESULTS, "*__*.json"))):
        with open(p) as fh:
            d = json.load(fh)
        data.setdefault(d["env"], {})[d["arm"]] = d
    return data


def cols(d):
    eps = d["episodes"]
    steps = np.array([e["steps"] for e in eps], dtype=float)
    hazard = np.array([1.0 if e["outcome"] in HAZARD else 0.0 for e in eps])
    goal = np.array([1.0 if e["outcome"] == "goal" else 0.0 for e in eps])
    budget_out = np.array([1.0 if e["outcome"] in ("fuel", "timeout") else 0.0
                           for e in eps])
    mind = np.array([e["min_goal_dist"] for e in eps], dtype=float)
    fgr = np.array([e["frac_steps_in_goal_region"] for e in eps], dtype=float)
    cells = np.array([e["cells_visited"] for e in eps], dtype=float)
    sim = np.array([e["sim_steps"] for e in eps], dtype=float)
    per_step = np.where(steps > 0, sim / np.maximum(steps, 1), 0.0)
    return dict(steps=steps, hazard=hazard, goal=goal, budget_out=budget_out,
                min_goal_dist=mind, frac_goal_region=fgr, cells=cells,
                sim_steps=sim, sim_per_step=per_step)


def survival_curve(c):
    """Fraction of episodes not yet dead at step t (goal counts as alive)."""
    steps, goal = c["steps"], c["goal"]
    return {t: float(np.mean((steps >= t) | (goal > 0))) for t in CURVE_T}


def main():
    data = load()
    summary = {}
    out = []
    out.append("# E4 tables (auto-generated by scripts/analyze_e4.py)\n")

    for env_name in ["trapgrid", "funnel"]:
        if env_name not in data:
            continue
        arms = data[env_name]
        C = {a: cols(arms[a]) for a in ARM_ORDER if a in arms}
        summary[env_name] = {}

        out.append(f"\n## {env_name}\n")
        out.append("### Main table\n")
        out.append("| arm | n | steps survived (CI95) | hazard death rate (CI95) "
                   "| goal rate (CI95) | used full budget (CI95) | "
                   "sim_steps / real step (CI95) |")
        out.append("|---|---|---|---|---|---|---|")
        for a in ARM_ORDER:
            if a not in C:
                continue
            c = C[a]
            n = len(c["steps"])
            row = dict(
                n=n,
                steps=boot_ci(c["steps"]),
                hazard=boot_ci(c["hazard"]),
                goal=boot_ci(c["goal"]),
                budget_out=boot_ci(c["budget_out"]),
                sim_per_step=boot_ci(c["sim_per_step"]),
                min_goal_dist=boot_ci(c["min_goal_dist"]),
                frac_goal_region=boot_ci(c["frac_goal_region"]),
                cells=boot_ci(c["cells"]),
                survival_curve=survival_curve(c),
                outcomes={},
            )
            for e in arms[a]["episodes"]:
                row["outcomes"][e["outcome"]] = row["outcomes"].get(e["outcome"], 0) + 1
            summary[env_name][a] = row
            out.append(
                f"| {ARM_LABEL[a]} | {n} | {fmt_ci(row['steps'])} | "
                f"{fmt_ci(row['hazard'], 3)} | {fmt_ci(row['goal'], 3)} | "
                f"{fmt_ci(row['budget_out'], 3)} | {fmt_ci(row['sim_per_step'], 0)} |"
            )

        out.append("\n### Goal-approach diagnostics (the sensitive P3 test)\n")
        out.append("| arm | n | min distance to goal reached (CI95) | "
                   "frac of steps in goal region (CI95) | distinct cells visited (CI95) |")
        out.append("|---|---|---|---|---|")
        for a in ARM_ORDER:
            if a not in C:
                continue
            r = summary[env_name][a]
            out.append(f"| {ARM_LABEL[a]} | {r['n']} | {fmt_ci(r['min_goal_dist'])} | "
                       f"{fmt_ci(r['frac_goal_region'], 3)} | {fmt_ci(r['cells'])} |")

        out.append("\n### Survival curves: fraction of episodes still alive at step t\n")
        out.append("| arm | n | " + " | ".join(f"t={t}" for t in CURVE_T) + " |")
        out.append("|---|---|" + "---|" * len(CURVE_T))
        for a in ARM_ORDER:
            if a not in C:
                continue
            r = summary[env_name][a]
            out.append(f"| {ARM_LABEL[a]} | {r['n']} | " +
                       " | ".join(f"{r['survival_curve'][t]:.2f}" for t in CURVE_T) + " |")

        out.append("\n### Pre-registered contrasts (bootstrap CI95 of the difference)\n")
        out.append("| prediction | contrast | metric | difference (CI95) |")
        out.append("|---|---|---|---|")
        contrasts = [
            ("P1", "a0g1", "random", "steps"),
            ("P1", "a0g1", "random", "hazard"),
            ("P2", "a0g1", "a0g0", "steps"),
            ("P2 (equal budget)", "a0g1", "a0g0_eq", "steps"),
            ("P2 (equal budget)", "a0g1", "a0g0_eq", "hazard"),
            ("P2 decomp: viability kill", "killdead_only", "a0g0_eq", "steps"),
            ("P2 decomp: viability kill", "killdead_only", "a0g0_eq", "hazard"),
            ("P2 decomp: graded cone", "a0g1", "killdead_only", "steps"),
            ("P2 decomp: graded cone", "a0g1", "killdead_only", "hazard"),
            ("P3", "a0g1", "random", "goal"),
            ("P3", "a0g1", "safe_random", "goal"),
            ("P3 (sensitive)", "a0g1", "random", "min_goal_dist"),
            ("P3 (sensitive)", "a0g1", "safe_random", "min_goal_dist"),
            ("P3 (sensitive)", "a0g1", "safe_random", "frac_goal_region"),
            ("control", "a0g1", "safe_random", "steps"),
            ("control", "a0g1", "safe_random", "hazard"),
        ]
        summary[env_name]["_contrasts"] = {}
        for pid, x, y, metric in contrasts:
            if x not in C or y not in C:
                continue
            d = boot_diff_ci(C[x][metric], C[y][metric])
            key = f"{pid}:{x}-{y}:{metric}"
            summary[env_name]["_contrasts"][key] = d
            nd = 3 if metric in ("hazard", "goal", "frac_goal_region") else 2
            out.append(f"| {pid} | {x} (n={len(C[x][metric])}) minus "
                       f"{y} (n={len(C[y][metric])}) | {metric} | {fmt_ci(d, nd)} |")

    dump_json(os.path.join(RESULTS, "summary.json"), summary)
    text = "\n".join(out) + "\n"
    with open(os.path.join(RESULTS, "tables.md"), "w") as fh:
        fh.write(text)
    print(text)


if __name__ == "__main__":
    main()
